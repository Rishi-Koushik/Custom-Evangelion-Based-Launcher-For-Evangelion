# Unit-01 keeps the exact colours the launcher shipped with; other units derive the same roles from their palette.
UNIT01_FIXED = dict(ink=0x0A0610, panel=0x120C1A, dock=0x120A1C, tile=0x221A2E, scrim=0x050310, sky_edge=0x04020A,
                    sky_low=0x1A0710, ridge=0x0E0616, low=0x0C0614, tower=0x07030D)


def mix(a, b, t):
    r = round(((a >> 16) & 255) * (1 - t) + ((b >> 16) & 255) * t)
    g = round(((a >> 8) & 255) * (1 - t) + ((b >> 8) & 255) * t)
    bl = round((a & 255) * (1 - t) + (b & 255) * t)
    return (r << 16) | (g << 8) | bl


def derive(u):
    d = u["deep"]
    if u["id"] == "unit01":
        out = dict(UNIT01_FIXED)
    else:
        out = dict(ink=mix(d, 0, 0.64), panel=mix(d, 0, 0.45), dock=mix(d, 0, 0.45), tile=mix(d, MUTED, 0.16),
                   scrim=mix(d, 0, 0.78), sky_edge=mix(d, 0, 0.85), sky_low=mix(d, 0, 0.74), ridge=mix(d, 0, 0.72),
                   low=mix(d, 0, 0.68), tower=mix(d, 0, 0.82))
    u.update(out)
    return u


def tones(u):
    """(gradient start, gradient end, glyph colour) for the four icon tones p / g / o / d, as #RRGGBB strings."""
    h = lambda c: "#%06X" % c
    if u["id"] == "unit01":
        return {"p": ("#8B5CD6", "#3A1F66", "#A3FF3A"), "g": ("#A3FF3A", "#517F1D", "#0B0612"),
                "o": ("#FF9A3A", "#C24200", "#170900"), "d": ("#2A1F37", "#0D0912", "#A3FF3A")}
    a, a2, deep, warn = u["a"], u["a2"], u["deep"], u["warn"]
    return {
        "p": (h(mix(a2, 0xFFFFFF, 0.18)), h(mix(a2, 0, 0.55)), h(a)),
        "g": (h(a), h(mix(a, 0, 0.5)), h(mix(deep, 0, 0.6))),
        "o": (h(mix(warn, 0xFFFFFF, 0.25)), h(mix(warn, 0, 0.24)), h(mix(deep, 0, 0.75))),
        "d": (h(mix(deep, MUTED, 0.18)), h(mix(deep, 0, 0.75)), h(a)),
    }


def argb(c):
    return "0xFF%06X" % c


def java_units(package, with_icons):
    rows = []
    for u in UNITS:
        fields = ", ".join([
            f'"{u["id"]}"', f'"{u["name"]}"', f'"{u["kanji"]}"', f'"{u["sub"]}"', f'"{u["suffix"]}"',
            argb(u["a"]), argb(u["a2"]), argb(u["deep"]), argb(u["warn"]), argb(u["sv"]), argb(u["svdim"]),
            argb(u["ink"]), argb(u["panel"]), argb(u["dock"]), argb(u["tile"]), argb(u["scrim"]),
            argb(u["sky_edge"]), argb(u["sky_low"]), argb(u["ridge"]), argb(u["low"]), argb(u["tower"])])
        rows.append(f"        new Unit({fields})")
    table = ",\n".join(rows)
    return f'''package {package};

/** GENERATED by nerv-os/tools/gen_units.py: edit the palette there, not here. */
final class Units {{
    static final int MUTED = 0xFF{MUTED:06X};

    static final class Unit {{
        final String id, name, kanji, sub, suffix;
        /** neon accent, body colour, deep background, warning colour, battery-saver colour and its dim variant */
        final int a, a2, deep, warn, sv, svDim;
        /** dark UI surfaces derived from the palette */
        final int ink, panel, dock, tile, scrim, skyEdge, skyLow, ridge, low, tower;

        Unit(String id, String name, String kanji, String sub, String suffix, int a, int a2, int deep, int warn, int sv, int svDim,
             int ink, int panel, int dock, int tile, int scrim, int skyEdge, int skyLow, int ridge, int low, int tower) {{
            this.id = id; this.name = name; this.kanji = kanji; this.sub = sub; this.suffix = suffix;
            this.a = a; this.a2 = a2; this.deep = deep; this.warn = warn; this.sv = sv; this.svDim = svDim;
            this.ink = ink; this.panel = panel; this.dock = dock; this.tile = tile; this.scrim = scrim;
            this.skyEdge = skyEdge; this.skyLow = skyLow; this.ridge = ridge; this.low = low; this.tower = tower;
        }}

        /** first word of the name, for tight spots like chips */
        String shortName() {{
            int i = name.indexOf(' ');
            return i < 0 ? name : name.substring(0, i);
        }}

        /** colour with a new alpha (0..1) */
        static int alpha(int colour, float a) {{
            return (Math.round(a * 255) << 24) | (colour & 0xFFFFFF);
        }}
    }}

    static final Unit[] ALL = {{
{table}
    }};

    static Unit byId(String id) {{
        for (Unit u : ALL) if (u.id.equals(id)) return u;
        return ALL[0];
    }}

    private Units() {{}}
}}
'''


def load_gen_icons():
    spec = importlib.util.spec_from_file_location("gen_icons", NERV / "iconpack" / "tools" / "gen_icons.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def write_wallpapers():
    """Live wallpaper entries (shown in Nothing's lock-screen customiser): one per unit."""
    names = {"unit01": "Misato Katsuragi", "unit00": "Unit-00 Rei", "unit02": "Unit-02 Asuka", "unit08": "Mari Unit-08"}
    classes = {"unit01": "WpUnit01", "unit00": "WpUnit00", "unit02": "WpUnit02", "unit08": "WpUnit08"}
    strings = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for u in UNITS:
        uid = u["id"]
        (LAUNCHER_RES / "drawable" / f"wp_thumb_{uid}.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n<shape xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <gradient android:angle="270" android:startColor="#{u["deep"]:06X}" android:centerColor="#{u["a2"]:06X}" '
            f'android:endColor="#{u["warn"]:06X}" />\n</shape>\n', encoding="utf-8")
        (LAUNCHER_RES / "xml" / f"wp_{uid}.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n<wallpaper xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:author="@string/wp_author" android:description="@string/wp_{uid}"\n'
            f'    android:thumbnail="@drawable/wp_thumb_{uid}" />\n', encoding="utf-8")
        strings.append(f'    <string name="wp_{uid}">NERV {names[uid]}: the whole phone follows this unit</string>')
        strings.append(f'    <string name="wp_label_{uid}">NERV · {names[uid]}</string>')
        (LAUNCHER_JAVA / f"{classes[uid]}.java").write_text(
            "package dev.nervos.home;\n\n/** Live wallpaper for one unit (generated by gen_units.py). */\n"
            f"public class {classes[uid]} extends UnitWallpaper {{\n    @Override\n    String unitId() {{\n        return \"{uid}\";\n    }}\n}}\n",
            encoding="utf-8", newline="\n")
    strings.append('    <string name="wp_author">NERV Home</string>')
    strings.append("</resources>")
    (LAUNCHER_RES / "values" / "strings.xml").write_text("\n".join(strings) + "\n", encoding="utf-8")


def main():
    for u in UNITS:
        derive(u)
    (LAUNCHER_JAVA / "Units.java").write_text(java_units("dev.nervos.home", True), encoding="utf-8", newline="\n")
    if QUICKSTAR_JAVA.exists():
        (QUICKSTAR_JAVA / "Units.java").write_text(java_units("dev.rishi.quickstar", False), encoding="utf-8", newline="\n")
    (GLYPH_JAVA / "Units.java").write_text(java_units("dev.nervos.glyph", False), encoding="utf-8", newline="\n")

    gi = load_gen_icons()
    drawable = LAUNCHER_RES / "drawable"
    written = 0
    for u in UNITS:
        if not u["suffix"]:
            continue
        gi.TONES.clear()
        gi.TONES.update(tones(u))
        for name, (tone, _) in gi.GLYPHS.items():
            (drawable / f"nerv_{name}{u['suffix']}.xml").write_text(gi.vector(name, tone), encoding="utf-8")
            (drawable / f"nerv_line_{name}{u['suffix']}.xml").write_text(gi.line_vector(name, "#%06X" % u["sv"]), encoding="utf-8")
            written += 2
    write_wallpapers()
    print(f"units written for launcher + quickstar + glyph; {written} icon drawables")


if __name__ == "__main__":
    main()
